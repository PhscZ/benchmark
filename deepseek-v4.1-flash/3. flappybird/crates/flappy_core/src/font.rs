//! Original 5x7 bitmap font, authored for this project.
//!
//! Storing the glyphs in source (rather than loading a TTF) means the native
//! and wasm builds share one text renderer, no font file has to be shipped or
//! downloaded, and there is no font licensing question at all.
//!
//! Each glyph is 7 rows of 5 pixels. Row bit 4 is the leftmost pixel, bit 0 the
//! rightmost, so the binary literals below read exactly like the rendered glyph.

pub const GLYPH_W: i32 = 5;
pub const GLYPH_H: i32 = 7;
/// Glyph width plus one column of tracking.
pub const ADVANCE: i32 = GLYPH_W + 1;

pub type Glyph = [u8; GLYPH_H as usize];

/// Horizontal anchoring for [`crate::gfx::Framebuffer::draw_text`].
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Align {
    Left,
    Center,
    Right,
}

const BLANK: Glyph = [0; 7];

